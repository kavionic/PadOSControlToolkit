#include "stdafx.h"

#include "PadOSControl/Core/SDCardSync/SDCardSyncState.h"

#include "PadOSControl/Core/SerialHandler.h"

#include <algorithm>
#include <utility>

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

SDCardSyncState::SDCardSyncState(Context context)
    : m_Context(std::move(context))
{
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

SDCardSyncState::~SDCardSyncState()
{
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::Cancel()
{
    FinishCanceled();
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

SerialHandler& SDCardSyncState::GetSerialHandler() const
{
    Q_ASSERT(m_Context.SerialHandler != nullptr);
    return *m_Context.SerialHandler;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

int32_t SDCardSyncState::GetSessionID() const
{
    return m_Context.SessionID;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::FinishSucceeded()
{
    Complete(CompletionStatus::Succeeded, QString());
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::FinishFailed(const QString& statusText)
{
    Complete(CompletionStatus::Failed, statusText);
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::FinishCanceled()
{
    Complete(CompletionStatus::Canceled, QString());
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::SetProgress(std::optional<float> totalProgress, std::optional<float> subProgress, const QString& progressText)
{
    if (ProgressChanged) {
        ProgressChanged(*this, ClampProgress(totalProgress), ClampProgress(subProgress), progressText);
    }
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::SetStatusText(const QString& statusText)
{
    if (StatusTextChanged) {
        StatusTextChanged(*this, statusText);
    }
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void SDCardSyncState::Complete(CompletionStatus status, const QString& statusText)
{
    if (!m_Completed)
    {
        m_Completed = true;
        if (StateCompleted) {
            StateCompleted(*this, status, statusText);
        }
    }
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

std::optional<float> SDCardSyncState::ClampProgress(std::optional<float> progress)
{
    if (!progress.has_value()) {
        return std::nullopt;
    }
    return std::clamp(*progress, 0.0f, 1.0f);
}
