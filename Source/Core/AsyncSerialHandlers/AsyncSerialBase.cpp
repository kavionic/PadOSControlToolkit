#include "stdafx.h"

#include "PadOSControl/Core/AsyncSerialHandlers/AsyncSerialBase.h"

#include <QObject>

static constexpr int ASYNC_SERIAL_OPERATION_TIMEOUT_MILLISECONDS = 100000;

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

AsyncSerialBase::AsyncSerialBase()
{
    m_TimeoutTimer.setSingleShot(true);
    m_TimeoutTimer.setInterval(ASYNC_SERIAL_OPERATION_TIMEOUT_MILLISECONDS);
    QObject::connect(&m_TimeoutTimer, &QTimer::timeout, &m_TimeoutTimer, [this]()
    {
        HandleTimeout();
    });
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

AsyncSerialBase::~AsyncSerialBase()
{
    StopTimeout();
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void AsyncSerialBase::StartTimeout()
{
    m_TimeoutTimer.start();
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void AsyncSerialBase::StopTimeout()
{
    m_TimeoutTimer.stop();
}
